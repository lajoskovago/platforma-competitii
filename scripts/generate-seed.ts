/**
 * Generates supabase/seed.sql from data/turneul1.json.
 *   npm run seed:generate
 * The seed is applied by `supabase db reset` (local) — it is idempotent
 * (on conflict do nothing), so it can also be run against production once.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Region = "SR5" | "SR6" | null;
interface Data {
  season: string;
  clubs: { name: string; city: string | null; region: Region }[];
  categories: {
    code: string;
    name: string;
    period: string;
    groups: { name: string; region: Region; notes?: string; teams: [string, string][] }[];
  }[];
}

const root = join(import.meta.dirname, "..");
const data: Data = JSON.parse(readFileSync(join(root, "data/turneul1.json"), "utf8"));

const q = (v: string | null | undefined) =>
  v == null ? "null" : `'${v.replace(/'/g, "''")}'`;

const clubNames = new Set(data.clubs.map((c) => c.name));
const out: string[] = [
  "-- GENERATED by scripts/generate-seed.ts from data/turneul1.json — do not edit by hand.",
  "",
  "-- Clubs",
];

for (const c of data.clubs) {
  out.push(
    `insert into public.clubs (name, city, region) values (${q(c.name)}, ${q(c.city)}, ${c.region ? `'${c.region}'` : "null"}) on conflict (name) do nothing;`,
  );
}

data.categories.forEach((cat, ci) => {
  out.push("", `-- ${cat.code}`);
  out.push(
    `insert into public.categories (code, name, sort_order) values (${q(cat.code)}, ${q(cat.name)}, ${ci + 1}) on conflict (scope, code) do nothing;`,
  );
  out.push(
    `insert into public.tournaments (category_id, season, number, name, period)
  select id, ${q(data.season)}, 1, 'Turneul 1', ${q(cat.period)} from public.categories where scope = 'regional' and code = ${q(cat.code)}
  on conflict (category_id, season, number) do nothing;`,
  );

  cat.groups.forEach((g, gi) => {
    out.push(
      `insert into public.groups (tournament_id, name, region, notes, sort_order)
  select t.id, ${q(g.name)}, ${g.region ? `'${g.region}'` : "null"}, ${q(g.notes)}, ${gi + 1}
    from public.tournaments t join public.categories c on c.id = t.category_id
   where c.scope = 'regional' and c.code = ${q(cat.code)} and t.season = ${q(data.season)} and t.number = 1
  on conflict (tournament_id, name) do nothing;`,
    );
    for (const [team, club] of g.teams) {
      if (!clubNames.has(club)) throw new Error(`Unknown club "${club}" for team "${team}"`);
      out.push(
        `insert into public.teams (club_id, category_id, name)
  select cl.id, c.id, ${q(team)} from public.clubs cl, public.categories c
   where cl.name = ${q(club)} and c.scope = 'regional' and c.code = ${q(cat.code)}
  on conflict (category_id, name) do nothing;`,
        `insert into public.group_teams (group_id, team_id)
  select gr.id, tm.id
    from public.groups gr
    join public.tournaments t on t.id = gr.tournament_id
    join public.categories c on c.id = t.category_id
    join public.teams tm on tm.category_id = c.id and tm.name = ${q(team)}
   where c.scope = 'regional' and c.code = ${q(cat.code)} and t.season = ${q(data.season)} and t.number = 1 and gr.name = ${q(g.name)}
  on conflict do nothing;`,
      );
    }
  });
});

writeFileSync(join(root, "supabase/seed.sql"), out.join("\n") + "\n");
const teamCount = data.categories.reduce((n, c) => n + c.groups.reduce((m, g) => m + g.teams.length, 0), 0);
console.log(`seed.sql written: ${data.clubs.length} clubs, ${data.categories.length} categories, ${teamCount} team entries`);
